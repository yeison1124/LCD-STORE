let currentCategory = "all";
let searchQuery = "";

function renderCaps() {
  const grid = document.getElementById("capGrid");
  const countBadge = document.getElementById("capCount");
  if (!grid) return;

  const query = searchQuery.toLowerCase().trim();
  const filtered = capsList.filter(cap => {
    const matchesCat = (currentCategory === "all" || cap.cat === currentCategory || 
      (currentCategory === "lujo" && ["lujo", "urbana"].includes(cap.cat)) ||
      (currentCategory === "deporte" && ["deporte", "beisbol", "mlb"].includes(cap.cat)) ||
      (currentCategory === "clasica" && ["clasica", "animal"].includes(cap.cat))
    );
    const matchesSearch = !query || 
      cap.name.toLowerCase().includes(query) || 
      cap.brand.toLowerCase().includes(query) || 
      cap.ref.toLowerCase().includes(query) ||
      (cap.desc && cap.desc.toLowerCase().includes(query));
    return matchesCat && matchesSearch;
  });

  if (countBadge) {
    countBadge.textContent = `${filtered.length} modelos disponibles`;
  }

  if (filtered.length === 0) {
    grid.innerHTML = `
      <div style="grid-column: 1/-1; text-align: center; padding: 60px 20px; color: rgba(255,255,255,0.4);">
        <p style="font-size: 40px; margin-bottom: 12px;">🔍</p>
        <h3 style="color: #fff; font-size: 18px; margin-bottom: 6px;">No encontramos gorras para "${searchQuery}"</h3>
        <p style="font-size: 14px;">Intenta con marcas como "Tommy", "Lacoste", "Gucci", "Monastery", "Béisbol", "Nike", "Yankees", etc.</p>
      </div>
    `;
    return;
  }

  const currentCart = typeof Cart !== "undefined" ? Cart.getItems() : [];

  grid.innerHTML = filtered.map(cap => {
    const inCartItem = currentCart.find(i => i.ref === cap.ref);
    const inCartQty = inCartItem ? inCartItem.qty : 0;
    const waMsg = encodeURIComponent(
      `Hola LCD Store 👋 Me interesa pedir esta gorra específica:\n\n` +
      `🧢 *${cap.name}*\n` +
      `• Código Ref: *${cap.ref}*\n` +
      `• Marca: *${cap.brand}*\n` +
      `• Precio Detal: *$${cap.price} BCV*\n` +
      `• Precio Mayor (+6 unid): *$9.50 BCV*\n\n` +
      `¿Tienen disponibilidad de este modelo exacto?`
    );
    const waUrl = `https://wa.me/584221602238?text=${waMsg}`;
    
    return `
      <article class="product-card" data-ref="${cap.ref}">
        <div class="product-image-wrap">
          <span class="product-badge">${cap.brand}</span>
          <span class="product-page-badge">Ref: ${cap.ref}</span>
          <img 
            src="./${cap.image}" 
            alt="${cap.name}" 
            loading="lazy"
            onerror="this.src='./logo.png';"
          />
        </div>
        <div class="product-info">
          <div class="product-header">
            <div>
              <span class="product-ref-label">Calidad AAA Importada</span>
              <h3 class="product-name">${cap.name}</h3>
            </div>
            <div class="product-price-box">
              <span class="price-val">$${cap.price}</span>
              <span class="price-bcv">BCV</span>
            </div>
          </div>
          <p class="product-notes">⚡ <b>Mayor (6+ unid): $9.50 BCV</b></p>
          <div class="product-actions">
            <button class="btn btn-add ${inCartQty > 0 ? 'added' : ''}" onclick="addCapToCart('${cap.ref}')">
              <svg width="15" height="15" viewBox="0 0 24 24" fill="currentColor"><path d="M19 13h-6v6h-2v-6H5v-2h6V5h2v6h6v2z"/></svg>
              <span>${inCartQty > 0 ? `✓ En pedido (${inCartQty})` : '+ Agregar al pedido'}</span>
            </button>
            <a class="btn btn-wa" href="${waUrl}" target="_blank" rel="noopener" title="Pedir este modelo por WhatsApp">
              <svg class="ico" width="16" height="16"><use href="#ico-wa"/></svg>
            </a>
          </div>
        </div>
      </article>
    `;
  }).join("");
}

window.addCapToCart = function(ref) {
  const cap = capsList.find(c => c.ref === ref);
  if (cap && typeof Cart !== "undefined") {
    Cart.addItem({
      ref: cap.ref,
      name: cap.name,
      brand: cap.brand,
      size: "Ajustable / Unitalla",
      price: parseFloat(cap.price) || 12,
      price_mayor: 9.5,
      is_cap: true,
      image: cap.image
    });
  }
};

window.refreshCardButtons = function() {
  renderCaps();
};

document.addEventListener("DOMContentLoaded", () => {
  renderCaps();

  const searchInput = document.getElementById("capSearch");
  const clearBtn = document.getElementById("clearCapSearch");
  if (searchInput) {
    searchInput.addEventListener("input", (e) => {
      searchQuery = e.target.value;
      if (clearBtn) clearBtn.style.display = searchQuery ? "block" : "none";
      renderCaps();
    });
  }

  if (clearBtn) {
    clearBtn.addEventListener("click", () => {
      if (searchInput) {
        searchInput.value = "";
        searchQuery = "";
        clearBtn.style.display = "none";
        renderCaps();
      }
    });
  }

  const filterTabs = document.querySelectorAll(".tab-btn");
  filterTabs.forEach(btn => {
    btn.addEventListener("click", () => {
      filterTabs.forEach(b => b.classList.remove("active"));
      btn.classList.add("active");
      currentCategory = btn.getAttribute("data-cat") || "all";
      renderCaps();
    });
  });
});
